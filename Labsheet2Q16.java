public class Labsheet2Q16 {
    public static void main(String[] args) {
        int num = 20;
        int multiplied = num << 3;
        int divided = num >> 2;

        System.out.println("Original Number: " + num);
        System.out.println(num + " * 8 (num << 3) = " + multiplied);
        System.out.println(num + " / 4 (num >> 2) = " + divided);
    }
}
